"""Verify parameter sections generated by the TBE adapter's own compilation path."""

from contextlib import ExitStack
import importlib
from pathlib import Path
import re
import struct
import sys
from tempfile import TemporaryDirectory
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "tools/build/asc_op_compile_base"))
from adapter import ascendc_compile_dfx as metadata
from adapter.ascendc_common_utility import CommonUtility, CompileInfo
from adapter.ascendc_constants import CompileOptionTuple, KernelMetaType
from adapter.get_op_tiling import TilingInfo
from adapter.global_storage import global_var_storage

compile_op = importlib.import_module("adapter.compile_op")


class TestKernelParamMetadata(unittest.TestCase):
    def setUp(self):
        stack = ExitStack()
        self.addCleanup(stack.close)
        folder = stack.enter_context(TemporaryDirectory())
        self.info = CompileInfo()
        self.info.src_file = "add.cpp"
        self.info.kernel_name = "add"
        self.info.origin_func_name = "add"
        self.info.gen_kernel_func_file = str(Path(folder) / "add_kernel.cpp")
        self.info.tiling_key_list = ["7"]
        self.tiling = TilingInfo()
        self.tiling.static_shape_flag = False
        self.op = compile_op.OpInfo(
            kernel_name="add",
            op_type="Add",
            inputs=[{"param_name": "x"}],
            outputs=[{"param_name": "y"}],
            origin_inputs=[],
            mc2_ctx=[],
        )
        for name, value in (
            ("ascendc_enable_super_kernel", False),
            ("ascendc_enable_sanitizer", True),
            ("ascendc_tiling_no_register", False),
            ("ascendc_enable_aicore_exception_restart", False),
        ):
            old = global_var_storage.get_variable(name)
            global_var_storage.set_variable(name, value)
            self.addCleanup(global_var_storage.set_variable, name, old)
        for name, value in (
            ("is_v220", True),
            ("is_v100", False),
            ("is_v200", False),
            ("is_c310", False),
            ("get_chip_version", "c220"),
        ):
            stack.enter_context(mock.patch.object(CommonUtility, name, return_value=value))
        stack.enter_context(mock.patch.object(compile_op, "get_current_build_config", return_value=[]))
        stack.enter_context(mock.patch.object(compile_op, "get_v220_kernel_type_mix_flag", return_value=(False, False)))
        metadata.DFXSectionGenerator().dfx_info_reset(self.op)

    def generate_source(self):
        compile_op.gen_kernel_fun(self.info, "add", self.op, self.tiling, CompileOptionTuple([], []))
        return Path(self.info.gen_kernel_func_file).read_text()

    def test_main_entry_layout_matches_final_dynamic_and_static_formals(self):
        for static, count in ((False, 4), (True, 3)):
            with self.subTest(static=static):
                self.tiling.static_shape_flag = static
                source = self.generate_source()
                self.assertNotIn("kernel_param_metadata", vars(self.info))
                self.assertIn('section(".ascend.meta." ASCENDC_PARAM_STRINGIFY(auto_gen_add_kernel))', source)
                initializer = source.split("g_ascendc_param_metadata_", 1)[1].split("= {", 1)[1].split("};", 1)[0]
                encoded = bytes(int(value, 16) for value in re.findall(r"0x[0-9a-f]{2}", initializer))
                self.assertEqual(struct.unpack_from("<HHIQ", encoded), (16, 12, count, count * 8))
                self.assertEqual(len(encoded), 16 + count * 40)
                for ordinal in range(count):
                    self.assertEqual(
                        struct.unpack_from("<HHIIIIHHIIII", encoded, 16 + ordinal * 40),
                        (17, 36, 0, ordinal, ordinal * 8, 8, 8, 2, 0, 0, 0, 0),
                    )

    def test_mix_slave_sections_stay_inside_their_entry_guards(self):
        self.info.tiling_key_group_map = {"7": ["8"]}
        self.info.tiling_key_kernel_type = {
            "7": KernelMetaType.KERNEL_TYPE_MIX_AIC_1_2,
            "8": KernelMetaType.KERNEL_TYPE_MIX_AIC_1_2,
        }
        source = self.generate_source()
        for core, entry in (("CUBE", "add_8_mix_aic"), ("VEC", "add_8_mix_aiv")):
            guard = f"#if TILING_KEY_VAR == 7UL && defined(__DAV_C220_{core}__)"
            block = source.split(guard, 1)[1].split("\n#if TILING_KEY_VAR", 1)[0]
            self.assertIn(f"void {entry}(", block)
            self.assertIn(f"ASCENDC_PARAM_STRINGIFY({entry})", block)

    def test_encoding_failure_keeps_existing_kernel_source(self):
        with mock.patch.object(metadata, "_serialize_param_metadata", side_effect=RuntimeError("encoding failure")):
            source = self.generate_source()
        self.assertIn("void auto_gen_add_kernel(", source)
        self.assertNotIn("g_ascendc_param_metadata_", source)

    def test_sk_keeps_existing_entry_without_ordinary_metadata(self):
        self.info.super_kernel_info = {"sp_options": {}}
        global_var_storage.set_variable("ascendc_enable_super_kernel", True)
        with mock.patch.object(compile_op, "get_context", return_value=None):
            source = self.generate_source()
        self.assertIn("void auto_gen_add_kernel(uint64_t args_offset)", source)
        self.assertNotIn("g_ascendc_param_metadata_", source)
